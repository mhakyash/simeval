module karnaugh_map(
  input wire A, B, C, D, E,
  output reg F
);

  always @*
    case ({A,B,C,D,E})
      5'b00000, 5'b00001, 5'b00101, 5'b00100, 5'b01110, 5'b11110, 5'b10110, 5'b10000: F = 1;
      5'b01000, 5'b01010, 5'b11010, 5'b11000: F = 0;
      5'b00010, 5'b00110, 5'b10100, 5'b10001: F = C;
      5'b01100, 5'b11100, 5'b01101, 5'b11101: F = !C;
      5'b01001, 5'b01011, 5'b11011, 5'b11001: F = B;
      5'b10010, 5'b10111, 5'b00111, 5'b00011: F = !B;
      5'b10010, 5'b10011, 5'b10111, 5'b10110: F = A;
      5'b01101, 5'b01111, 5'b11111, 5'b11101: F = !A;
    endcase

endmodule